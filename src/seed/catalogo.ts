function juego(
  titulo: string,
  descripcion: string,
  generos: JuegoSeed['generos'],
  plataformas: JuegoSeed['plataformas'],
  caracteristicas: JuegoSeed['caracteristicas'],
  urlImagen: string | undefined = PORTADAS[titulo],
  metadatos: Pick<JuegoSeed, 'desarrollador' | 'fechaLanzamiento'> = {},
): JuegoSeed {
  return {
    titulo,
    descripcion,
    urlImagen,
    generos,
    ...metadatos,
    plataformas: [...plataformas],
    caracteristicas,
  };
}

